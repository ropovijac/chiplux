class _DiscoverIconPainter extends CustomPainter {
  final DiscoverCategory category;
  final int? genreId;
  final Color color;
  _DiscoverIconPainter(this.category, this.genreId, this.color);
  @override
  void paint(Canvas canvas, Size size) {
    final glyph =
        _discoverGlyphs['${category.name}:${genreId ?? 0}'] ??
        _discoverGlyphs['${category.name}:0']!;
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = 2
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    canvas.save();
    canvas.scale(size.width / 40, size.height / 40);
    for (final outline in glyph.paths) {
      final path = Path()..moveTo(outline[0], outline[1]);
      for (var i = 2; i < outline.length; i += 2) {
        path.lineTo(outline[i], outline[i + 1]);
      }
      canvas.drawPath(path, paint);
    }
    for (final circle in glyph.circles) {
      canvas.drawCircle(Offset(circle[0], circle[1]), circle[2], paint);
    }
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant _DiscoverIconPainter old) =>
      old.category != category || old.genreId != genreId || old.color != color;
}
